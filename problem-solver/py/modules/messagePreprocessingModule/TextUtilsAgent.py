class TextUtilsAgent(ScAgentClassic):
    def __init__(self):
        super().__init__("action_text_utils")

    def on_event(self, event_element: ScAddr, event_edge: ScAddr, action_element: ScAddr) -> ScResult:
        result = self.run(action_element)
        is_successful = result == ScResult.OK
        finish_action_with_status(action_element, is_successful)
        self.logger.info("TextUtilsAgent finished %s",
                         "successfully" if is_successful else "unsuccessfully")
        return result

    def run(self, action_node: ScAddr) -> ScResult:
        self.logger.info("TextUtilsAgent started")

        try:
            message_addr = get_action_arguments(action_node, 1)[0]
            string_content = get_link_content_data(message_addr)[0]
            self.logger.info(string_content)
        except:
            self.logger.info(f"TextUtilsAgent: finished with an error")
            return ScResult.ERROR
        return ScResult.OK